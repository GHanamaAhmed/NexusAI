#!/usr/bin/env node
/**
 * Writes src/data.ts, the wilayas and communes, from the MIT-licensed
 * GeoAlgeria dataset (https://github.com/yasserstudio/geoalgeria):
 *
 *   npm pack geoalgeria@1.3.0 && tar xzf geoalgeria-1.3.0.tgz
 *   node scripts/generate.mjs /path/to/package
 *
 * The output is committed, so this only runs when the dataset changes. It
 * stops if the data doesn't add up: wrong counts, a new wilaya without its
 * former wilaya, a commune of a wilaya that doesn't exist.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const VERSION = "1.3.0"
const here = path.dirname(fileURLToPath(import.meta.url))
const source = process.argv[2]
if (!source) {
  console.error(
    "Usage: node scripts/generate.mjs <unpacked geoalgeria package>"
  )
  process.exit(1)
}

const read = (file) =>
  JSON.parse(fs.readFileSync(path.join(source, file), "utf8"))
const fail = (message) => {
  console.error(`generate: ${message}`)
  process.exit(1)
}

const pkg = read("package.json")
if (pkg.version !== VERSION) {
  fail(`expected GeoAlgeria ${VERSION}, got ${pkg.version}`)
}
const { wilayas } = read("data/wilayas.json")
const communes = read("data/ecommerce/communes.json")
if (wilayas.length !== 69) fail(`expected 69 wilayas, got ${wilayas.length}`)
if (communes.length !== 1541) {
  fail(`expected 1541 communes, got ${communes.length}`)
}

const outWilayas = wilayas
  .map((w) => {
    // Wilayas 59-69 (2026) name the wilaya they were taken from.
    const parent = w.code <= 58 ? w.code : w.mother_wilaya_code
    if (!Number.isInteger(parent) || parent < 1 || parent > 58) {
      fail(`wilaya ${w.code} has no former wilaya (got ${parent})`)
    }
    if (!w.name_ar || !w.name_fr) fail(`wilaya ${w.code} is missing a name`)
    return { code: w.code, parent, ar: w.name_ar, fr: w.name_fr }
  })
  .sort((a, b) => a.code - b.code)

const codes = new Set(outWilayas.map((w) => w.code))
const outCommunes = communes
  .map((c) => {
    if (!codes.has(c.wilaya_code)) {
      fail(`commune ${c.id} has unknown wilaya ${c.wilaya_code}`)
    }
    if (!c.commune_name_ar || !c.commune_name_fr) {
      fail(`commune ${c.id} is missing a name`)
    }
    return {
      wilaya: c.wilaya_code,
      ar: c.commune_name_ar,
      fr: c.commune_name_fr,
    }
  })
  .sort((a, b) => a.wilaya - b.wilaya || a.fr.localeCompare(b.fr, "fr"))

const line = (value) =>
  `  { ${Object.entries(value)
    .map(([key, v]) => `${key}: ${JSON.stringify(v)}`)
    .join(", ")} },`
const out = [
  `// Generated by scripts/generate.mjs from GeoAlgeria ${VERSION} (MIT, see LICENSE-DATA.md). Do not edit.`,
  `import type { Commune, Wilaya } from "./types.js"`,
  ``,
  `export const WILAYAS: readonly Wilaya[] = [`,
  ...outWilayas.map(line),
  `]`,
  ``,
  `export const COMMUNES: readonly Commune[] = [`,
  ...outCommunes.map(line),
  `]`,
  ``,
].join("\n")

const file = path.join(here, "..", "src", "data.ts")
fs.writeFileSync(file, out)
console.log(
  `Wrote ${outWilayas.length} wilayas and ${outCommunes.length} communes to ${path.relative(process.cwd(), file)}`
)
